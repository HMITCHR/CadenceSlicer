// density: sparse infill density. The 0.4/0.8 pair needs more sparse work than the 0.2 pairs before its coarse bands
// clearly pay for the tower and the tool changes.
struct CoarsePair { double fine_nozzle, coarse_nozzle, fine, coarse; int ratio; double density; };

// A stepped part (100 mm block 7.2 mm tall, 28 mm column to 14.4 mm) on a U1 refitted to the pair, shells deep enough
// for a coarse band, coarse tools flowing more. With `walls`: three loops and parts whose walls are seen from above.
Scene coarse_feature_scene(const CoarsePair &pair, bool walls)
{
    DynamicPrintConfig config = u1_config({pair.fine_nozzle, pair.fine_nozzle, pair.coarse_nozzle, pair.coarse_nozzle});
    config.set_key_value("wipe_tower_x", new ConfigOptionFloats{140.});
    config.set_key_value("wipe_tower_y", new ConfigOptionFloats{40.});
    feature_split_heights(config, pair.fine, pair.coarse, pair.ratio, 1, 3, {pair.fine_nozzle, pair.coarse_nozzle});
    config.set_key_value("sparse_infill_density", new ConfigOptionPercent(pair.density));
    config.set_key_value("filament_max_volumetric_speed", new ConfigOptionFloats{20., 20., 40., 40.});
    const int shells = 2 * pair.ratio + 3;
    config.set_key_value("top_shell_layers", new ConfigOptionInt(shells));
    config.set_key_value("bottom_shell_layers", new ConfigOptionInt(shells));
    if (walls)
        config.set_key_value("wall_loops", new ConfigOptionInt(3));
    return plate_scene(config, [walls, fine = pair.fine, ratio = pair.ratio](Model &model) {
        ModelObject *object = model.add_object();
        object->name = "coarse-feature-step";
        if (walls)
            for (int k = 0; k < ratio; ++k)
                add_part(object, make_cube(2., 18., 2. + k * fine), Vec3d(4. + 4. * k, 70., 7.2));
        add_part(object, make_cube(100., 100., 7.2), Vec3d::Zero());
        add_part(object, make_cube(28., 28., 14.4), Vec3d(36., 36., 0.));
        if (walls) {
            add_part(object, make_cone(14., 14.4), Vec3d(85., 85., 0.));
            add_part(object, make_cone(22., 3.6), Vec3d(70., 25., 7.2));
        }
        place(object, Vec3d(20., 20., 0.));
    });
}
