// The fine height the tool changer scenes print at on a fine/coarse pair.
double fine_height(const std::vector<double> &pair) { return pair[0] < .3 ? .08 : .12; }

// The largest whole multiple of the fine height the third tool (the coarse one) can lay.
int largest_ratio(const DynamicPrintConfig &config, double fine)
{
    return int(std::floor(config.option<ConfigOptionFloats>("max_layer_height")->get_at(2) / fine + 1e-6));
}

// The G-code without its "; generated by" header line (it carries the time).
std::string unstamped(const std::string &gcode) { return std::regex_replace(gcode, std::regex("; generated by [^\\n]*\\n"), ""); }

// Solid infill, tops and bottoms of the volume on its own filament (Feature Split sends them to the fine filament).
void own_surfaces(ModelVolume *volume, int filament)
{
    for (const char *key : {"internal_solid_filament_id", "top_surface_filament_id", "bottom_surface_filament_id"})
        volume->config.set_key_value(key, new ConfigOptionInt(filament));
}

ModelVolume *add_part(ModelObject *object, TriangleMesh mesh, const Vec3d &offset, int filament = 0)
{
    ModelVolume *volume = object->add_volume(std::move(mesh), ModelVolumeType::MODEL_PART, false);
    volume->set_offset(offset);
    if (filament > 0)
        volume->config.set_key_value("extruder", new ConfigOptionInt(filament));
    return volume;
}

void place(ModelObject *object, const Vec3d &offset)
{
    object->add_instance();
    object->instances.front()->set_offset(offset);
    object->ensure_on_bed();
}

// A scene on a non-Bambu printer: `add` puts the plate's objects in the model, then the config is applied.
Scene plate_scene(DynamicPrintConfig config, std::function<void(Model &)> add)
{
    Scene scene;
    scene.bambu = false;
    scene.config = std::move(config);
    scene.populate = [add = std::move(add)](Model &model, Print &print, const DynamicPrintConfig &given) {
        add(model);
        print.apply(model, given);
        print.set_status_silent();
    };
    return scene;
}

// Slices the scene and requires G-code.
Facts sliced(const Scene &scene, PrintConfig *resolved = nullptr)
{
    Facts facts = slice(scene, resolved);
    INFO(facts.refusal.string);
    REQUIRE(facts.refusal.string.empty());
    REQUIRE_FALSE(facts.gcode.empty());
    return facts;
}

// A non-Bambu scene at `fine` and `coarse`: Body Split on a body pair (filaments 1 and `coarse_filament`), or Feature
// Split on a box with 40 % sparse infill on `coarse_filament`, centred at `at`.
Scene split_scene(DynamicPrintConfig config, bool body, double fine, double coarse, int ratio, int coarse_filament,
                  const std::vector<double> &pair, const Vec2d &at)
{
    Scene scene;
    scene.bambu = false;
    scene.config = std::move(config);
    if (body)
        body_split_heights(scene.config, fine, coarse, ratio, pair);
    else {
        feature_split_heights(scene.config, fine, coarse, ratio, 1, coarse_filament, pair);
        scene.config.set_key_value("sparse_infill_density", new ConfigOptionPercent(40.));
    }
    scene.populate = [body, coarse, coarse_filament, at](Model &model, Print &print, const DynamicPrintConfig &config) {
        if (body)
            load_body_pair(model, print, config, at, 1, coarse_filament, coarse);
        else
            load_feature_box(model, print, config, at);
    };
    return scene;
}

// Slices the scene, then changes its config the way an edit in the app does: applied to the same Print, sliced again.
std::pair<Facts, Facts> slice_then_change(Scene scene, const std::function<void(DynamicPrintConfig &)> &change)
{
    mixed_nozzle_fixtures::fill_per_filament_values(scene.config);
    Model model;
    Print print;
    print.is_BBL_printer() = scene.bambu;
    scene.populate(model, print, scene.config);
    print.set_status_silent();
    Facts before = slice(print);
    change(scene.config);
    print.apply(model, scene.config);
    Facts after = slice(print);
    return {std::move(before), std::move(after)};
}
