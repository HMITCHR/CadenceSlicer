// A U1 with tools fine, fine, coarse, and fine with PETG (its own adhesion category): Organic support on
// `support_filament` under a gapless PETG interface, the tower inside the toolhead clearance (lag ceiling two coarse
// layers), Feature Split at `ratio` times the fine height (0: the largest the coarse tool takes).
DynamicPrintConfig crowded_config(const std::vector<double> &pair, int support_filament = 1, int ratio = 0)
{
    DynamicPrintConfig config = u1_config({pair[0], pair[0], pair[1], pair[0]});
    auto &types = config.option<ConfigOptionStrings>("filament_type", true)->values;
    auto &categories = config.option<ConfigOptionInts>("filament_adhesiveness_category", true)->values;
    types.resize(4, "PLA");
    categories.resize(4, 100);
    types[3] = "PETG";
    categories[3] = 300;
    config.set_key_value("enable_support", new ConfigOptionBool(true));
    config.set_key_value("support_type", new ConfigOptionEnum<SupportType>(stTreeAuto));
    config.set_key_value("support_style", new ConfigOptionEnum<SupportMaterialStyle>(smsTreeOrganic));
    config.set_key_value("support_filament", new ConfigOptionInt(support_filament));
    config.set_key_value("support_interface_filament", new ConfigOptionInt(4));
    config.set_key_value("support_top_z_distance", new ConfigOptionFloat(0.));
    config.set_key_value("support_bottom_z_distance", new ConfigOptionFloat(0.));
    config.set_key_value("support_interface_top_layers", new ConfigOptionInt(2));
    config.set_key_value("support_interface_bottom_layers", new ConfigOptionInt(0));
    config.set_key_value("wipe_tower_x", new ConfigOptionFloats{149.});
    config.set_key_value("wipe_tower_y", new ConfigOptionFloats{110.});
    const double fine = fine_height(pair);
    if (ratio == 0)
        ratio = largest_ratio(config, fine);
    feature_split_heights(config, fine, fine * ratio, ratio, 1, 3, pair);
    config.set_key_value("sparse_infill_density", new ConfigOptionPercent(15.));
    config.set_key_value("outer_wall_filament_id", new ConfigOptionInt(0));
    config.set_key_value("inner_wall_filament_id", new ConfigOptionInt(0));
    return config;
}

